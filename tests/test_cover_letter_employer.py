"""Regression tests for cover-letter employer attribution.

The defect (D3) was a false ``INVENTED_EMPLOYER`` on letters generated by the
offline provider for a profile whose confirmed experience employer is
"Independent AI & Data Science Development". The letter was correct -- it named
the candidate's own confirmed employer -- but validation rejected it.

Two compounding validator defects caused it, both in
``services/validation.py::validate_cover_letter``:

1. ``Index.employers()`` canonicalises employers with ``normalize_title``, which
   strips punctuation, so the confirmed employer is ``"independent ai data
   science development"``. The sentence guard compared that against
   ``normalize_text`` output, which *keeps* the "&"::

       "independent ai data science development" in "at independent ai & data science development ..."
       -> False     (never matches for any punctuated employer name)

   The guard exists precisely to skip sentences about the candidate's own
   history, so it was inert and every such sentence fell through to the
   employer probe.

2. That probe is ``\\b[Aa]t\\s+([A-Z][\\w&.\\-]*(?:\\s+[A-Z][\\w&.\\-]*){0,2})``,
   which cannot continue past "&", so it captured ``"Independent AI"``. The
   follow-up containment test requires the known employer to fit inside the
   captured name; a strict prefix never does.

These tests drive the real generator and then the real validator. No network,
no database, no AI provider configuration.
"""

from __future__ import annotations

import pytest
from app.ai.offline_provider import OfflineProvider
from app.services.normalization import normalize_text, normalize_title
from app.services.validation import validate_cover_letter
from app.schemas import ProfileSummary

# The employer name that triggered the defect: it contains an ampersand.
PUNCTUATED_EMPLOYER = "Independent AI & Data Science Development"

JOB_DESCRIPTION = """\
Senior Data Scientist at Example Analytics.

Required: Python, SQL, and 5+ years of experience in production machine learning.
You will build and evaluate statistical models and data pipelines.
"""


def _profile(employers: list[tuple[str, str]], projects: list[dict] | None = None) -> ProfileSummary:
    """Build a confirmed profile with the given (company, title) experience rows."""
    return ProfileSummary(
        id=1,
        name="Test Candidate",
        professional_title="Data Scientist",
        location="Lagos, Nigeria",
        years_of_experience=6,
        summary="Data professional with experience in quantitative analysis.",
        skills=[
            {"id": 1, "name": "Python"},
            {"id": 2, "name": "SQL"},
        ],
        experience=[
            {
                "id": i + 1,
                "company": company,
                "title": title,
                "start_date": "2021",
                "end_date": None,
                "is_current": True,
                "description": f"Built data pipelines in Python at {company}.",
            }
            for i, (company, title) in enumerate(employers)
        ],
        projects=projects or [],
    )


def _generate_and_validate(
    profile: ProfileSummary, job_title: str, company: str | None
) -> tuple[str, list]:
    """Run the real offline generator, then the real validator."""
    letter = OfflineProvider().generate_cover_letter(
        profile=profile,
        job_description=JOB_DESCRIPTION,
        job_title=job_title,
        company=company,
    )
    report = validate_cover_letter(
        letter, profile, job_title, company, job_description=JOB_DESCRIPTION
    )
    return letter, report.issues


def _codes(issues) -> list[str]:
    return [i.code for i in issues]


# --------------------------------------------------- the defect itself


def test_punctuated_confirmed_employer_is_not_reported_as_invented() -> None:
    """Requirement 1: job with a known employer + the punctuated employer name."""
    profile = _profile([(PUNCTUATED_EMPLOYER, "Self-Directed Professional Development")])
    letter, issues = _generate_and_validate(profile, "Data Scientist", "Example Analytics")

    invented = [i for i in issues if i.code == "INVENTED_EMPLOYER"]
    assert not invented, [i.message for i in invented]
    # The letter must still name the confirmed employer it is talking about.
    assert PUNCTUATED_EMPLOYER in letter


def test_project_title_does_not_override_the_real_employer() -> None:
    """Requirement 1/2: the project title exists but the job employer is real."""
    profile = _profile(
        [(PUNCTUATED_EMPLOYER, "Self-Directed Professional Development")],
        projects=[
            {
                "id": 1,
                "name": PUNCTUATED_EMPLOYER,
                "description": "Built models in Python.",
                "technologies": ["Python"],
            }
        ],
    )
    letter, issues = _generate_and_validate(profile, "Data Scientist", "Example Analytics")

    assert "INVENTED_EMPLOYER" not in _codes(issues), [i.message for i in issues]
    # The greeting must address the actual hiring employer, not the project.
    assert "Dear Example Analytics hiring team," in letter
    assert "Dear Independent" not in letter


def test_other_known_employer_is_not_overridden_by_project_title() -> None:
    """Requirement 2: a different job employer must survive intact."""
    profile = _profile(
        [("Monzo", "Data Scientist"), (PUNCTUATED_EMPLOYER, "Researcher")],
        projects=[{"id": 1, "name": PUNCTUATED_EMPLOYER, "description": "",
                   "technologies": []}],
    )
    letter, issues = _generate_and_validate(profile, "Data Scientist", "SEAhub Asia")

    assert "INVENTED_EMPLOYER" not in _codes(issues), [i.message for i in issues]
    assert "Dear SEAhub Asia hiring team," in letter


def test_missing_employer_produces_a_neutral_salutation() -> None:
    """Requirement 3: no confirmed employer -> no invented company name."""
    profile = _profile([(PUNCTUATED_EMPLOYER, "Self-Directed Professional Development")])
    letter, issues = _generate_and_validate(profile, "Data Scientist", None)

    assert "INVENTED_EMPLOYER" not in _codes(issues), [i.message for i in issues]
    # Neutral, non-fabricated greeting.
    assert "Dear your team hiring team," in letter
    assert "Example Analytics" not in letter


# ------------------------------------- the guard must still bite when it should


def test_genuinely_unsupported_employer_is_still_rejected() -> None:
    """Requirement 4: the safeguard must survive the fix."""
    profile = _profile([("Monzo", "Data Scientist")])
    letter = (
        "Dear Example Analytics hiring team,\n\n"
        "I am applying for the Data Scientist role.\n\n"
        "At Globex Corporation I led the modelling team and built pipelines "
        "in Python and SQL.\n\n"
        "Kind regards,\nTest Candidate"
    )
    issues = validate_cover_letter(
        letter, profile, "Data Scientist", "Example Analytics",
        job_description=JOB_DESCRIPTION,
    ).issues

    invented = [i for i in issues if i.code == "INVENTED_EMPLOYER"]
    assert invented, "an invented employer must still be reported"
    assert "Globex Corporation" in invented[0].message


def test_invented_employer_next_to_a_confirmed_one_is_still_rejected() -> None:
    """Requirement 4: the fix must not let a real employer mask a fake one."""
    profile = _profile([(PUNCTUATED_EMPLOYER, "Self-Directed Professional Development")])
    letter = (
        "Dear Example Analytics hiring team,\n\n"
        "I am applying for the Data Scientist role.\n\n"
        f"At {PUNCTUATED_EMPLOYER} I built data pipelines in Python.\n\n"
        "At Initech Solutions I owned the platform roadmap and led delivery.\n\n"
        "Kind regards,\nTest Candidate"
    )
    issues = validate_cover_letter(
        letter, profile, "Data Scientist", "Example Analytics",
        job_description=JOB_DESCRIPTION,
    ).issues

    invented = [i for i in issues if i.code == "INVENTED_EMPLOYER"]
    assert invented, "Initech must still be reported"
    assert any("Initech" in i.message for i in invented)


def test_normal_letter_keeps_its_supported_employer_attribution() -> None:
    """Requirement 5: ordinary, well-supported attribution is untouched."""
    profile = _profile([("Monzo", "Data Scientist"), ("SEAhub Asia", "Data Analyst")])
    letter, issues = _generate_and_validate(profile, "Data Scientist", "Example Analytics")

    assert "INVENTED_EMPLOYER" not in _codes(issues), [i.message for i in issues]
    assert "At Monzo I " in letter
    assert "At SEAhub Asia I " in letter


# ------------------------------------------- the normalisers must agree


def test_employer_guard_compares_like_for_like() -> None:
    """Pin the root cause: the two canonicalisers used to disagree."""
    sentence = f"At {PUNCTUATED_EMPLOYER} I built pipelines."
    known = normalize_title(PUNCTUATED_EMPLOYER)

    assert normalize_text(sentence).find(known) == -1, (
        "precondition for the defect: raw normalize_text does not contain it"
    )
    assert known in normalize_title(normalize_text(sentence)), (
        "the guard must match once both sides use normalize_title"
    )
